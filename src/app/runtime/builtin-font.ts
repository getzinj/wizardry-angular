// Line-drawing pieces. The game's second font replaces a stretch of punctuation with these, and
// the screen frame is drawn by printing those punctuation characters: see the border, rules and
// column divider built in SPECIALS.TEXT.txt (SCRNOUTL, HORZLINE, INITSCRN).
const VERTICAL: number = 0x08;   // column 3 of the cell
const HORIZONTAL: number = 0x7F; // all seven pixels of one row
const RIGHTWARD: number = 0x78;  // columns 3..6, meeting a vertical from the right
const LEFTWARD: number = 0x0F;   // columns 0..3

function box(above: number, middle: number, below: number): readonly number[] {
  return [above, above, above, middle, below, below, below, below];
}

const GRAPHICS_OVERRIDES: Readonly<Record<string, readonly number[]>> = {
  '!': box(0x00, RIGHTWARD, VERTICAL),        // top-left corner
  '"': box(0x00, HORIZONTAL, 0x00),           // horizontal run
  '#': box(0x00, LEFTWARD, VERTICAL),         // top-right corner
  '$': box(VERTICAL, VERTICAL, VERTICAL),     // vertical run
  '%': box(VERTICAL, RIGHTWARD, 0x00),        // bottom-left corner
  '&': box(VERTICAL, LEFTWARD, 0x00),         // bottom-right corner
  "'": box(VERTICAL, RIGHTWARD, VERTICAL),    // tee opening right
  '(': box(VERTICAL, LEFTWARD, VERTICAL),     // tee opening left
  '[': box(0x00, HORIZONTAL, VERTICAL),       // tee opening down
  '\\': box(VERTICAL, VERTICAL, VERTICAL),    // vertical run
  ']': box(VERTICAL, RIGHTWARD, VERTICAL),    // tee opening right
  '^': box(VERTICAL, HORIZONTAL, 0x00),       // tee opening up
};
 


/** Lowest character the font covers; the game indexes its glyph table by code point minus this. */
export const FIRST_GLYPH_CHARACTER: number = 32;

/** Glyphs in a font: character codes 32 to 95. */
export const GLYPH_COUNT: number = 64;


function buildFont(overrides: Readonly<Record<string, readonly number[]>>): Uint8Array {
  const font: Uint8Array = new Uint8Array(GLYPH_COUNT * GLYPH_HEIGHT);

  for (let index: number = 0; index < GLYPH_COUNT; index++) {
    const character: string = String.fromCharCode(FIRST_GLYPH_CHARACTER + index);
    const glyph: readonly number[] | undefined = overrides[character] ?? TEXT_GLYPHS[character];

    if (glyph != null) {
      font.set(glyph, index * GLYPH_HEIGHT);
    }
  }

  return font;
}


/** Stand-in for the font the game loads from the block after its table of contents. */
export const BUILTIN_TEXT_FONT: Uint8Array = buildFont({});

/** Stand-in for the line-drawing font the game loads from the block after that one. */
export const BUILTIN_GRAPHICS_FONT: Uint8Array = buildFont(GRAPHICS_OVERRIDES);
